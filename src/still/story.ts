/**
 * ΑΚΟΜΑ ΕΓΩ — the story.
 *
 * Six chapters. Each chapter is a tableau (the set) plus an ordered list
 * of beats (the words). The StoryScene plays the beats one at a time:
 * lines type out and wait for a click, choices show buttons, titles fade.
 *
 * The choices CONVERGE — by design. Whatever the player picks, the truth
 * is the same. That is the whole point of the story: there is no door.
 * The choices change a sentence, a shade of tone — never the destination.
 *
 * `chill` runs 0 → 1 across the six chapters: the world drains of warmth
 * as the narrator understands more. The StoryScene feeds it to the
 * post-FX pipeline (cold shift + grain).
 *
 * Text is Greek — the language the story was written in.
 */

export type BeatTone = "normal" | "inner" | "reader";

export interface LineBeat {
  kind: "line";
  text: string;
  /** "inner" = a knife thought (cool tint). "reader" = addressed to YOU. */
  tone?: BeatTone;
}

export interface TitleBeat {
  kind: "title";
  text: string;
  sub?: string;
}

export interface ChoiceBeat {
  kind: "choice";
  /** Each option shows a button; picking it prints `reply`, then the story
   *  continues — all options lead to the same next beat. */
  options: { label: string; reply: string }[];
}

export type Beat = LineBeat | TitleBeat | ChoiceBeat;

export interface Chapter {
  id: number;
  /** Tableau registry key (see src/scenes/still/tableaux). */
  tableau: string;
  /** Ambient audio key, or "" for silence. */
  ambient: string;
  /** 0 = warm, 1 = drained. Drives the post-FX cold/grain. */
  chill: number;
  beats: Beat[];
}

